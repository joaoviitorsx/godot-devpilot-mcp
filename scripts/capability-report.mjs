import { readFileSync, readdirSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dispatcherPath = path.join(repo, "addons", "godot_devpilot_mcp", "core", "dispatcher.gd");
const outputPath = path.join(repo, "addons", "godot_devpilot_mcp", "core", "capability_methods.gd");
const manifestPath = path.join(repo, "docs", "capability_manifest.json");
const source = readFileSync(dispatcherPath, "utf8");
const dispatch = source.slice(source.indexOf("func dispatch("), source.indexOf("func _health_check("));
if (!dispatch) throw new Error("Dispatcher method block was not found.");
const methods = [...dispatch.matchAll(/^\s{0,2}\t\t"([a-z][a-z0-9_]*\.[a-z0-9_]+)":/gm)].map((match) => match[1]);
if (methods.length < 40 || new Set(methods).size !== methods.length) throw new Error("Dispatcher method inventory is incomplete or has duplicates.");
const generated = `# Generated by scripts/capability-report.mjs. Do not edit manually.\n@tool\nextends RefCounted\n\nconst METHODS = [\n${methods.map((method) => `\t"${method}",`).join("\n")}\n]\n`;
const require = createRequire(path.join(repo, "mcp-server", "package.json"));
const ts = require("typescript");
const toolsDir = path.join(repo, "mcp-server", "src", "tools");
const index = readFileSync(path.join(repo, "mcp-server", "src", "index.ts"), "utf8");
const registrations = new Map();
const modeRank = { minimal: 0, core: 1, full: 2, agentic: 3, unknown: 4 };
for (const match of index.matchAll(/import\s*\{([^}]+)\}\s*from\s*"\.\/tools\/([^"/]+)\.js"/g)) {
  for (const name of match[1].split(",").map((part) => part.trim())) {
    if (!name) continue;
    const callAt = index.indexOf(`${name}(server,`);
    const coreAt = index.indexOf('if (config.mode !== "minimal")');
    const fullAt = index.indexOf('if (config.mode === "full"');
    const agenticAt = index.indexOf('if (config.mode === "agentic"');
    const mode = callAt < 0 ? "unknown" : callAt >= agenticAt ? "agentic" : callAt >= fullAt ? "full" : callAt >= coreAt ? "core" : "minimal";
    const previous = registrations.get(match[2]) ?? "unknown";
    if (modeRank[mode] < modeRank[previous]) registrations.set(match[2], mode);
  }
}
const readOnlySource = readFileSync(path.join(repo, "mcp-server", "src", "safety", "permissions.ts"), "utf8");
const readOnlyBlock = readOnlySource.slice(readOnlySource.indexOf("const READ_ONLY_TOOL_ALLOWLIST"), readOnlySource.indexOf("export function isToolAllowedInReadOnly"));
const readOnly = new Set([...readOnlyBlock.matchAll(/"([a-z][a-z0-9_]+)"/g)].map((match) => match[1]));
const tools = [];
const referencedMethods = new Set();
let dynamicRegistrations = 0;
const categorize = (name) => {
  if (/tile|terrain|gridmap|dungeon/.test(name)) return "tiles_and_levels";
  if (/gltf|asset|import|resource|material|texture/.test(name)) return "assets_and_resources";
  if (/nav|pathfind/.test(name)) return "navigation";
  if (/physics|collision|rigid|character_body/.test(name)) return "physics";
  if (/audio|sound|music|bus/.test(name)) return "audio";
  if (/anim|blend/.test(name)) return "animation";
  if (/shader|particle|vfx/.test(name)) return "visual_effects";
  if (/export|build|release/.test(name)) return "export";
  if (/runtime|run_project|playtest|replay|fps|screenshot|input|debug/.test(name)) return "runtime_and_testing";
  if (/scene|node|camera|lighting|mesh/.test(name)) return "scenes_and_nodes";
  if (/script|classdb|signal/.test(name)) return "scripting";
  if (/project|autoload|file|memory|context/.test(name)) return "project";
  if (/ui|menu|hud|accessibility/.test(name)) return "interface";
  return "workflow";
};
for (const file of readdirSync(toolsDir).filter((name) => name.endsWith(".ts"))) {
  const content = readFileSync(path.join(toolsDir, file), "utf8");
  const tree = ts.createSourceFile(file, content, ts.ScriptTarget.Latest, true);
  const literal = (node) => node && ts.isStringLiteral(node) ? node.text : null;
  const visit = (node) => {
    if (ts.isCallExpression(node)) {
      const callee = node.expression;
      if (ts.isPropertyAccessExpression(callee) && callee.expression.getText(tree) === "server" && ["tool", "registerTool"].includes(callee.name.text)) {
        const name = literal(node.arguments[0]);
        if (!name) dynamicRegistrations++;
        else {
          const config = node.arguments[1];
          let description = literal(config) ?? "";
          if (ts.isObjectLiteralExpression(config)) {
            const field = config.properties.find((prop) => ts.isPropertyAssignment(prop) && prop.name.getText(tree) === "description");
            if (field) description = literal(field.initializer) ?? "";
          }
          let schema = node.arguments[2];
          if (callee.name.text === "registerTool" && ts.isObjectLiteralExpression(config)) {
            const field = config.properties.find((prop) => ts.isPropertyAssignment(prop) && prop.name.getText(tree) === "inputSchema");
            schema = field?.initializer;
          }
          const parameters = ts.isObjectLiteralExpression(schema) ? schema.properties.filter(ts.isPropertyAssignment).map((field) => ({ name: field.name.getText(tree).replace(/^['"]|['"]$/g, ""), optional: field.initializer.getText(tree).includes(".optional()") })) : [];
          const rpcMethods = new Set();
          const collectRpc = (child) => {
            if (ts.isCallExpression(child)) {
              const target = child.expression;
              const argument = ts.isPropertyAccessExpression(target) && target.expression.getText(tree) === "godot" && target.name.text === "call" ? child.arguments[0] : ["callAfterConnect", "call"].includes(target.getText(tree)) && child.arguments[0]?.getText(tree) === "godot" ? child.arguments[1] : null;
              const rpc = literal(argument);
              if (rpc && /^[a-z][a-z0-9_]*\.[a-z0-9_]+$/.test(rpc)) rpcMethods.add(rpc);
            }
            ts.forEachChild(child, collectRpc);
          };
          collectRpc(node);
          tools.push({ name, category: categorize(name), min_mode: registrations.get(file.slice(0, -3)) ?? "unknown", min_godot: name.includes("better_tile_editor") ? "4.6" : "4.3", effect: readOnly.has(name) ? "read" : "write_or_unknown", description, parameters, rpc_methods: [...rpcMethods].sort(), source: `mcp-server/src/tools/${file}` });
        }
      }
      const methodArg = ts.isPropertyAccessExpression(callee) && callee.expression.getText(tree) === "godot" && callee.name.text === "call" ? node.arguments[0] : ["callAfterConnect", "call"].includes(callee.getText(tree)) && node.arguments[0]?.getText(tree) === "godot" ? node.arguments[1] : null;
      const method = literal(methodArg);
      if (method && /^[a-z][a-z0-9_]*\.[a-z0-9_]+$/.test(method)) referencedMethods.add(method);
    }
    ts.forEachChild(node, visit);
  };
  visit(tree);
}
tools.sort((a, b) => a.name.localeCompare(b.name));
const missingMethods = [...referencedMethods].filter((method) => !methods.includes(method)).sort();
const manifest = JSON.stringify({ generated_by: "scripts/capability-report.mjs", minimum_godot: "4.3", rpc_methods: methods, tools, dynamic_registrations: dynamicRegistrations, missing_rpc_methods: missingMethods }, null, 2) + "\n";
if (process.argv.includes("--check")) {
  const existing = readFileSync(outputPath, "utf8").replace(/\r\n/g, "\n");
  if (existing !== generated) throw new Error("RPC inventory is stale. Run node scripts/capability-report.mjs.");
  if (readFileSync(manifestPath, "utf8").replace(/\r\n/g, "\n") !== manifest) throw new Error("Capability manifest is stale. Run node scripts/capability-report.mjs.");
} else {
  writeFileSync(outputPath, generated);
  writeFileSync(manifestPath, manifest);
}
if (missingMethods.length) throw new Error(`MCP references missing RPC methods: ${missingMethods.join(", ")}`);
console.log(JSON.stringify({ rpc_methods: methods.length, tools: tools.length, dynamic_registrations: dynamicRegistrations, missing_rpc_methods: missingMethods, verified: process.argv.includes("--check") }));
